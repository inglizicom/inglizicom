/**
 * pronunciation-course.ts — content for the /admin/present/pronunciation deck.
 * «ليغو الإنجليزية» — connected speech for Arabic speakers, A0 → A2.
 *
 * THE PROMISE: understand fast speech, and stop sounding like a list of words.
 * Every lesson is one brick. Bricks snap together into chunks, chunks into sentences.
 *
 * ── The notation (used inside every ENGLISH string) ────────────────────────────
 *   word~word   a LINK: the consonant jumps onto the next vowel   (will~always)
 *   word=word   TWIN consonants: one long sound, not two          (black=coffee)
 *   word^word   a GLIDE sneaks in, /j/ or /w/                     (I^am → I-yam)
 *   word+word   a linking R                                        (far+away)
 *   (x)         a sound that DISAPPEARS                            (nex(t) day)
 *   *word*      a BEAT — the syllable the sentence leans on        (*bro*ther)
 * Arabic strings never carry notation.
 *
 * ── The sound-spelling ────────────────────────────────────────────────────────
 * `say` fields are a FIXED system, not free transliteration:
 *   • syllables joined by hyphens          bruh-ther
 *   • the stressed syllable in CAPITALS    bruh-THER
 *   • the lazy vowel is always `uh`        uh-BAWT (about)
 *
 * NAMES ARE NOT THE LESSON: beginners want a better mouth, not terminology. Say
 * «الصوت الكسول», not «الشوا»; a technical label may appear once, in brackets,
 * never in a title and never as the point of a slide.
 *   • never spell a sound Arabic already owns with the wrong letter —
 *     brother is `bruh-THER` (ذ), NOT `brada`. Teaching ذ→د installs an accent.
 * The sound-spelling is a crutch: real spelling always stays on screen above it,
 * and the deck lets you hide it (H) once a class stops needing it.
 */

export type Ex = { en: string; ar: string }

/** Two words one sound apart — the ear trainer. */
export type Pair = { a: string; b: string; sayA: string; sayB: string; ar: string }
/** One LEGO brick: a chunk said as a single word. */
export type Brick = { en: string; say: string; ar: string }
/** The same sentence at three speeds — the heart of the course. */
export type Gear = { en: string; slow: string; natural: string; fast: string; ar: string; why?: string }
/** A sentence to clap: *stars* mark the beats. */
export type Beat = { en: string; ar: string; note?: string }
/** What fast speech SOUNDS like vs what was actually said. */
export type Decode = { heard: string; real: string; ar: string }
/** Repeat-after-me line. */
export type Drill = { en: string; say: string }

/** Which letters make this sound — and where the same letters do something else. */
export type Spelling = { pattern: string; sound: string; examples: string; ar: string; warn?: string; warnAr?: string }
/** A sentence to say out loud. `check` is the self-test: how you KNOW you were right. */
export type Practice = { en: string; say: string; ar: string; check: string; checkAr: string }

export type Lesson = {
  no: number
  tag: string; tagAr: string
  title: string; titleAr: string
  ipa?: string                 // the sound this lesson owns, shown huge on the cover
  goal: Ex                     // the promise, one line
  trap: Ex                     // what Arabic does that breaks this — the reason the lesson exists
  how: Ex[]                    // mouth mechanics (sounds) or the rule (linking), 3–5 points
  pairs?: Pair[]
  bricks?: Brick[]
  beats?: Beat[]
  gears?: Gear[]
  decode?: Decode[]
  drill?: Drill[]
}

