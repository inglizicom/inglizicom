/**
 * Narrative layer for the dedicated per-package pages (/pricing/[plan]).
 *
 * data/plans.ts stays the single source of truth for anything commercial
 * (price, perks, duration). This file only adds the *story* around it:
 * the transformation, the week-by-week journey, and the objections we answer.
 *
 * Every plan falls back to a sensible default, so adding a plan to plans.ts
 * never produces a broken page — it just gets the generic narrative until
 * someone writes a specific one here.
 */

import type { Plan } from './plans'

