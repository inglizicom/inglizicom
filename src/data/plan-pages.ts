/* ── Classes: one generic narrative, parameterised by session count ────────── */

function classesPage(plan: Plan): PlanPage {
  const n = plan.sessionsIncluded ?? 1
  return {
    promise_ar: n === 1
      ? 'حصة واحدة 1:1 — تشخيص حقيقي لمستواك وخطة تعرف بها من أين تبدأ.'
      : `${n} حصص فردية مع الأستاذ — برنامج مصمّم لهدفك أنت، لا لمجموعة.`,
    before_ar: 'الدروس المسجّلة وحدها لا تكفيك — تحتاج شخصاً يسمعك ويصحّحك في اللحظة.',
    after_ar: n === 1
      ? 'تعرف بالضبط أين مستواك، وما الخطوة التالية، وأين ينزلق نطقك.'
      : 'تتكلم بثقة مع تصحيح فوري في كل حصة ومتابعة بينها على واتساب.',
    journey: [
      { when: 'الحصة 1',    title: 'التشخيص',        desc: 'نقيس مستواك الحقيقي ونحدّد هدفك، ونبني خطة الحصص عليه.' },
      ...(n > 1 ? [{ when: `الحصص 2-${n}`, title: 'التدريب المكثّف', desc: 'كلام مباشر مع تصحيح فوري للنطق والتركيب — 1h30 لكل حصة.' }] : []),
      ...(n >= 8 ? [{ when: 'بين الحصص', title: 'المتابعة', desc: 'واجبات صوتية ومتابعة على واتساب حتى لا يضيع ما بنيناه.' }] : []),
    ],
    objections: [
      {
        q: 'كيف تُحجز الحصص؟',
        a: 'بعد التفعيل نتفق معك على المواعيد حسب جدولك. الحصة 1h30 عبر Google Meet.',
      },
      ...(n > 1 ? [{
        q: 'هل تنتهي صلاحية الحصص؟',
        a: `الحصص الـ${n} مخصّصة لك — نجدولها معك ضمن ${plan.duration_months} ${plan.duration_months === 1 ? 'شهر' : 'أشهر'}، مع مرونة إذا طرأ ظرف.`,
      }] : []),
    ],
  }
}

/* ── Generic fallback ──────────────────────────────────────────────────────── */

function fallbackPage(plan: Plan): PlanPage {
  return {
    promise_ar: plan.subtitle_ar,
    before_ar:  'تعرف أن الإنجليزية تنقصك، ولا تعرف من أين تُمسك الخيط.',
    after_ar:   plan.lifetimePerks[0] ?? 'تتكلم بثقة في المواقف التي كانت تخيفك.',
    journey: [
      { when: 'البداية', title: 'الانطلاق', desc: plan.lifetimePerks[0] ?? '' },
      { when: 'المسار',  title: plan.followUpLabel_ar, desc: plan.followUpDuration_ar },
      { when: 'النهاية', title: 'النتيجة',  desc: plan.idealFor_ar ?? '' },
    ],
    objections: [],
  }
}

/** Full narrative for a plan — always returns something renderable. */
export function getPlanPage(plan: Plan): PlanPage {
  const base = PAGES[plan.id] ?? (plan.isClass ? classesPage(plan) : fallbackPage(plan))
  return { ...base, objections: [...base.objections, ...SHARED_OBJECTIONS] }
}

