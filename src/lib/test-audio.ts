/* ── Ambient bed ────────────────────────────────────────────────────────── */

/** A minor pentatonic across two octaves — no interval in it can clash. */
const SCALE = [220.00, 261.63, 293.66, 349.23, 392.00, 440.00, 523.25, 587.33, 698.46]

let bed: {
  master: GainNode
  timer: number
  stopped: boolean
} | null = null

/**
 * Start the background pad. Idempotent — calling it twice does nothing.
 * Must be triggered by a user gesture or the browser will refuse.
 */
export function startMusic(volume = 0.055): void {
  const c = audio()
  if (!c || bed) return

  const master = c.createGain()
  master.gain.setValueAtTime(0.0001, c.currentTime)
  master.gain.exponentialRampToValueAtTime(volume, c.currentTime + 3)

  // a gentle low-pass keeps it behind the voice rather than beside it
  const filter = c.createBiquadFilter()
  filter.type = 'lowpass'
  filter.frequency.value = 1100
  filter.Q.value = 0.4

  master.connect(filter)
  filter.connect(c.destination)

  const state = { master, timer: 0, stopped: false }
  bed = state

  /** One long, soft note. Two detuned oscillators give it body. */
  function voice(freq: number, dur: number) {
    const cc = audio()
    if (!cc || state.stopped) return
    const g = cc.createGain()
    g.gain.setValueAtTime(0.0001, cc.currentTime)
    g.gain.exponentialRampToValueAtTime(0.5, cc.currentTime + dur * 0.35)
    g.gain.exponentialRampToValueAtTime(0.0001, cc.currentTime + dur)
    g.connect(state.master)

    for (const detune of [-4, 4]) {
      const o = cc.createOscillator()
      o.type = 'sine'
      o.frequency.value = freq
      o.detune.value = detune
      o.connect(g)
      o.start()
      o.stop(cc.currentTime + dur + 0.1)
    }
  }

  function step() {
    if (state.stopped) return
    // a slow random walk, occasionally doubling at the fifth
    const root = SCALE[Math.floor(Math.random() * SCALE.length)]
    voice(root, 6 + Math.random() * 4)
    if (Math.random() < 0.45) {
      const other = SCALE[Math.floor(Math.random() * SCALE.length)]
      if (other !== root) setTimeout(() => voice(other, 5 + Math.random() * 3), 900)
    }
    state.timer = window.setTimeout(step, 3200 + Math.random() * 2600)
  }

  step()
}

export function stopMusic(): void {
  const c = audio()
  if (!bed) return
  const b = bed
  bed = null
  b.stopped = true
  clearTimeout(b.timer)
  if (c) {
    try {
      b.master.gain.cancelScheduledValues(c.currentTime)
      b.master.gain.setValueAtTime(b.master.gain.value, c.currentTime)
      b.master.gain.exponentialRampToValueAtTime(0.0001, c.currentTime + 1.2)
      setTimeout(() => { try { b.master.disconnect() } catch { /* already gone */ } }, 1500)
    } catch { /* context may be closed */ }
  }
}

export function musicPlaying(): boolean { return bed !== null }

/** Drop the bed while a listening clip plays, then bring it back. */
export function duckMusic(seconds: number): void {
  const c = audio()
  if (!bed || !c) return
  const g = bed.master.gain
  const now = c.currentTime
  const level = g.value
  try {
    g.cancelScheduledValues(now)
    g.setValueAtTime(level, now)
    g.exponentialRampToValueAtTime(Math.max(0.0001, level * 0.12), now + 0.25)
    g.exponentialRampToValueAtTime(level, now + seconds + 0.6)
  } catch { /* ignore */ }
}
