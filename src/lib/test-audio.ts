/* ══════════════════════════════════════════════════════════════════════════
   TEST AUDIO — synthesised, not sampled
   ══════════════════════════════════════════════════════════════════════════

   Every sound here is generated by the Web Audio API at runtime. Nothing is
   downloaded and nothing is licensed, which sidesteps the whole question of
   rights over "royalty-free" loops — you cannot infringe a waveform you
   computed yourself.

   The background bed is a slow pentatonic pad. Pentatonic because no two notes
   in it can clash, so an endless random walk never produces a sour interval;
   slow because the point is concentration, not entertainment. It sits about
   18 dB under the effects and ducks whenever a question is being spoken.
   ══════════════════════════════════════════════════════════════════════════ */

let ctx: AudioContext | null = null

function audio(): AudioContext | null {
  if (typeof window === 'undefined') return null
  if (!ctx) {
    const AC = window.AudioContext ?? (window as unknown as { webkitAudioContext?: typeof AudioContext }).webkitAudioContext
    if (!AC) return null
    ctx = new AC()
  }
  // Browsers suspend the context until a gesture; resume is a no-op if running.
  if (ctx.state === 'suspended') void ctx.resume()
  return ctx
}

/** Call once from a click handler so later sounds are allowed to play. */
export function unlockAudio(): void { audio() }

/* ── Effects ────────────────────────────────────────────────────────────── */

type Note = { f: number; t: number; d: number; type?: OscillatorType; gain?: number }

function play(notes: Note[], master = 0.18) {
  const c = audio()
  if (!c) return
  const bus = c.createGain()
  bus.gain.value = master
  bus.connect(c.destination)

  for (const n of notes) {
    const osc = c.createOscillator()
    const g = c.createGain()
    osc.type = n.type ?? 'sine'
    osc.frequency.setValueAtTime(n.f, c.currentTime + n.t)
    // a short attack and an exponential tail — square edges click audibly
    g.gain.setValueAtTime(0.0001, c.currentTime + n.t)
    g.gain.exponentialRampToValueAtTime(n.gain ?? 1, c.currentTime + n.t + 0.012)
    g.gain.exponentialRampToValueAtTime(0.0001, c.currentTime + n.t + n.d)
    osc.connect(g); g.connect(bus)
    osc.start(c.currentTime + n.t)
    osc.stop(c.currentTime + n.t + n.d + 0.02)
  }
}

